type PlatformId = keyof typeof PLATFORMS;

const ICON_SIZE = 18;

function PlatformSvg({ path, label }: { path: string; label: string }) {
  return (
    <svg
      viewBox="0 0 18 18"
      width={ICON_SIZE}
      height={ICON_SIZE}
      aria-label={label}
      fill="currentColor"
    >
      <path d={path} />
    </svg>
  );
}

export function PlatformIcon({ platformId }: { platformId: number }) {
  const platform = PLATFORMS[platformId as PlatformId];
  if (!platform) return null;

  return (
    <Tooltip title={platform.name}>
      <Box
        component="span"
        sx={{
          display: "inline-flex",
          alignItems: "center",
          lineHeight: 0,
          color: "text.secondary",
        }}
      >
        <PlatformSvg path={platform.path} label={platform.name} />
      </Box>
    </Tooltip>
  );
}

export function PlatformIcons({ platformIds }: { platformIds: number[] | undefined }) {
  if (!platformIds || platformIds.length === 0) return null;

  return (
    <Box
      component="span"
      sx={{
        display: "inline-flex",
        alignItems: "center",
        gap: 0.25,
        ml: 0.5,
      }}
    >
      {platformIds.map((id) => (
        <PlatformIcon key={id} platformId={id} />
      ))}
    </Box>
  );
}
